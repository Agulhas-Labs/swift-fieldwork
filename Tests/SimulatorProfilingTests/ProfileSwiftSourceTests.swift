import Foundation
@testable import SimulatorProfiling
@testable import SimulatorServices
import Testing

/// Covers the Swift source written for a profile and the command line flags of the health stage.
struct ProfileSwiftSourceTests {
    private let profile = ServiceProfile(
        profileVersion: 1,
        runtime: ProfileRuntime(identifier: "com.apple.CoreSimulator.SimRuntime.iOS-27-0", version: "27.0", build: "1A1"),
        deviceType: "iPhone 17",
        generated: "2026-01-01",
        method: ProfileMethod(costWindowSeconds: 30, footprintThresholdMB: 4, cpuThresholdSeconds: 0.5, checks: ["boot"]),
        services: [ServiceEntry(label: "a.b", domain: .daemon, start: .onDemand, ranAtBoot: true, peakFootprintMB: 5, cpuSeconds: 1, disposition: .keptByHealth)],
        capabilities: [:]
    )

    @Test func `the source is the registry convention`() throws {
        let expected = """
        // Copyright 2026 Agulhas Labs
        // SPDX-License-Identifier: Apache-2.0

        // Generated by simulator-profile; regenerate, don't edit.

        extension ServiceProfiles {
            /// The service profile measured on com.apple.CoreSimulator.SimRuntime.iOS-27-0.
            static let iOS27Point0: [String: String] = ["com.apple.CoreSimulator.SimRuntime.iOS-27-0": #\"\"\"
            {
              "capabilities" : {

              },
              "deviceType" : "iPhone 17",
              "generated" : "2026-01-01",
              "method" : {
                "checks" : [
                  "boot"
                ],
                "costWindowSeconds" : 30,
                "cpuThresholdSeconds" : 0.5,
                "footprintThresholdMB" : 4,
                "keptForInput" : [

                ]
              },
              "profileVersion" : 1,
              "runtime" : {
                "build" : "1A1",
                "identifier" : "com.apple.CoreSimulator.SimRuntime.iOS-27-0",
                "version" : "27.0"
              },
              "schemaVersion" : 1,
              "services" : [
                {
                  "cpuSeconds" : 1,
                  "disposition" : "keptByHealth",
                  "domain" : "daemon",
                  "label" : "a.b",
                  "peakFootprintMB" : 5,
                  "ranAtBoot" : true,
                  "start" : "onDemand"
                }
              ]
            }
            \"\"\"#]
        }

        """

        #expect(try ProfileSwiftSource.render(profile) == expected)
        #expect(try ProfileSwiftSource.registryLine(profile) == "iOS27Point0,")
    }

    @Test func `the rendered JSON decodes back to the profile`() throws {
        let decoded = try JSONDecoder().decode(ServiceProfile.self, from: Data(ProfileSwiftSource.json(profile).utf8))

        #expect(decoded == profile)
    }

    @Test func `names come from the runtime identifier`() throws {
        #expect(try ProfileSwiftSource.name(forRuntime: "com.apple.CoreSimulator.SimRuntime.iOS-27-0") == "iOS27Point0")
        #expect(try ProfileSwiftSource.name(forRuntime: "com.apple.CoreSimulator.SimRuntime.tvOS-26-4-1") == "tvOS26Point4Point1")
        #expect(throws: ProfileUsageError.self) { try ProfileSwiftSource.name(forRuntime: "") }
    }

    @Test func `every bundled profile file is what the generator renders from it`() throws {
        let directory = URL(filePath: #filePath)
            .deletingLastPathComponent() // SimulatorProfilingTests
            .deletingLastPathComponent() // Tests
            .deletingLastPathComponent() // the repository root
            .appending(path: "Sources/SimulatorServices/Profiles")
        let files = try FileManager.default.contentsOfDirectory(atPath: directory.path).filter { $0.hasSuffix(".swift") }.sorted()
        let identifiers = ServiceProfiles.bundled.keys.sorted()

        #expect(try files == identifiers.map { try "\(ProfileSwiftSource.name(forRuntime: $0)).swift" }.sorted())
        for identifier in identifiers {
            let profile = try #require(ServiceProfiles.profile(forRuntime: identifier))
            let file = try directory.appending(path: "\(ProfileSwiftSource.name(forRuntime: identifier)).swift")
            #expect(try ProfileSwiftSource.render(profile) == String(contentsOf: file, encoding: .utf8))
        }
    }

    private func parse(_ extra: [String]) throws -> ProfileOptions {
        try ProfileOptions.parse(["--runtime", "r", "--device-type", "d", "--out", "o.json"] + extra)
    }

    @Test func `the health flags have their defaults`() throws {
        let options = try parse([])

        #expect(options.stage == .all)
        #expect(options.logWindow == 45)
        #expect(options.maxKept == 12)
        #expect(options.app == nil)
        #expect(options.candidates == nil)
    }

    @Test func `the health flags are read`() throws {
        let options = try parse([
            "--app", "A.app", "--bundle-id", "x.y", "--xctestrun", "t.xctestrun", "--only-testing", "T/t",
            "--log-window", "15", "--max-kept", "3", "--stage", "cost", "--candidates", "a, b,,c", "--swift", "p.swift",
        ])

        #expect(options.app == "A.app")
        #expect(options.bundleID == "x.y")
        #expect(options.xctestrun == "t.xctestrun")
        #expect(options.onlyTesting == "T/t")
        #expect(options.logWindow == 15)
        #expect(options.maxKept == 3)
        #expect(options.stage == .cost)
        #expect(options.candidates == ["a", "b", "c"])
        #expect(options.swift == "p.swift")
    }

    @Test func `flags that go together are refused alone`() {
        #expect(throws: ProfileUsageError.self) { try parse(["--app", "A.app"]) }
        #expect(throws: ProfileUsageError.self) { try parse(["--bundle-id", "x"]) }
        #expect(throws: ProfileUsageError.self) { try parse(["--xctestrun", "t"]) }
        #expect(throws: ProfileUsageError.self) { try parse(["--only-testing", "t"]) }
    }

    @Test func `the health stage needs a profile to read, and only it takes one`() throws {
        #expect(throws: ProfileUsageError.self) { try parse(["--stage", "health"]) }
        #expect(throws: ProfileUsageError.self) { try parse(["--from", "p.json"]) }
        #expect(try parse(["--stage", "health", "--from", "p.json"]).from == "p.json")
        #expect(throws: ProfileUsageError.self) { try parse(["--stage", "nope"]) }
    }
}
